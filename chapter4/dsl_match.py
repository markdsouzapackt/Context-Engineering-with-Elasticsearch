import os

from elasticsearch import Elasticsearch
from elasticsearch.helpers import bulk
from dotenv import load_dotenv

load_dotenv()  # reads variables from a .env file and sets them in os.environ

es = Elasticsearch(
    os.environ["ELASTICSEARCH_URL"],
    api_key=os.environ["ELASTICSEARCH_API_KEY"],
)

# Be sure to have the index created by chapter3/mapping_and_index.py before running this script.
INDEX_NAME = "rag_context_chunks"

print(f"Search 1: match 'ranking pattern api'...")

response = es.search(
    index=INDEX_NAME,
    query={
        "match": {
            "chunk_text": {
                "query": "ranking pattern api"
            }
        }
    }
)

print("Results:")
for hit in response["hits"]["hits"]:
    print(hit["_id"], hit["_score"], hit["_source"]["section_heading"])


print(f"Search 2: match 'ranking pattern api' with minimum should match...")

# Of the optional terms generated by this query, at least 75% must match
# 75% of 3 = 2.25 that is rounded down to 2 terms that must match

response = es.search(
    index=INDEX_NAME,
    query={
        "match": {
            "chunk_text": {
                "query": "ranking pattern api",
                "minimum_should_match": "75%"
            }
        }
    }
)

print("Results:")
for hit in response["hits"]["hits"]:
    print(hit["_id"], hit["_score"], hit["_source"]["section_heading"])

